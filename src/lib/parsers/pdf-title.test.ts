import { describe, expect, it } from "vitest";
import { titleFromPdfText } from "./pdf-title";

const front =
  "Под общей редакцией профессора И. Л. Туккеля Санкт-Петербург «БХВ-Петербург» 2013 " +
  "УДК 338.2 Т38 Туккель, И. Л. Т38 Методы и инструменты управления инновационным развитием промышленных предприятий / И. Л. Туккель, С. А. Голубев / Под ред.";

describe("titleFromPdfText", () => {
  it("берёт название и первого автора из библиографической строки", () => {
    expect(titleFromPdfText(front)).toEqual({
      title: "Методы и инструменты управления инновационным развитием промышленных предприятий",
      author: "И. Л. Туккель",
    });
  });
});
